    assert(!st_chain_arm());
    uintptr_t page = (uintptr_t)path_transform_observer_page & ~(uintptr_t)(GATE_PAGE - 1);
    assert(!mprotect((void *)page, GATE_PAGE, PROT_READ | PROT_WRITE | PROT_EXEC));
