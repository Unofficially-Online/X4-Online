static void test_path_transform_observer(void) {
    unsigned char from[0x208] = {0}, to[0x208] = {0}, controller[16] = {0}, manager[0x400] = {0};
    const lxw_class *object_class = NULL, *movement_class = NULL, *nav_class = NULL;
    for (unsigned i = 0; i < LXW_CLASS_COUNT; ++i) {
        if (!object_class && lxw_classes[i].family == LXW_FAMILY_NONE && (lxw_classes[i].flags & 4u)) object_class = &lxw_classes[i];
        if (!movement_class && lxw_classes[i].family == LXW_FAMILY_STATIC) movement_class = &lxw_classes[i];
        if (!nav_class && lxw_classes[i].family == LXW_FAMILY_NAV) nav_class = &lxw_classes[i];
    }
    assert(object_class && movement_class && nav_class);
    void *object_vtable = LX(object_class->linux_vtable), *movement_vtable = LX(movement_class->linux_vtable);
    void *nav_vtable = LX(nav_class->linux_vtable), *target = to, *controller_ptr = controller, *manager_ptr = manager;
    memcpy(from, &object_vtable, 8);
    memcpy(from + LXW_OBJ_PARENT, &target, 8);
    memcpy(from + LXW_OBJ_CONTROLLER, &controller_ptr, 8);
    memcpy(controller, &movement_vtable, 8);
    put64(from + 8, 123);
    put64(to + 8, 456);
    void *previous_manager = NULL;
    memcpy(&previous_manager, LX(LX_PATH_MANAGER_VA), 8);
    double time = 17.0;
    memcpy(manager + PATH_TRANSFORM_OBSERVER_MANAGER_TIME, &time, 8);
    memcpy(LX(LX_PATH_MANAGER_VA), &manager_ptr, 8);
    world_identity_entry *previous_identities = world_identities;
    int previous_sealed = world_identity_sealed;
    int64_t previous_count = world_identity_count;
    world_identities = calloc(WORLD_IDENTITY_CAPACITY, sizeof(*world_identities));
    assert(world_identities);
    world_identity_sealed = 0;
    world_identity_count = 0;
    assert(world_identity_record(123, 0x111) && world_identity_record(456, 0x222));
    world_identity_sealed = 1;
    path_transform_observer_test_native = path_transform_observer_test_native_call;
    path_transform_observer_test_live = path_transform_observer_test_live_call;
    path_transform_observer_test_native_calls = path_transform_observer_test_live_calls = 0;
    path_transform_observer_installed = 1;
    stats.active = 1;
    boot_phase = 3;
    stats.issued = 10;
    path_transform_observer_from_tick = 10;
    path_transform_observer_to_tick = 10;
    path_pass_open = 1;
    path_transform_observer_scope_thread = 0;
    path_transform_observer_failures = 0;
    path_transform_observer_seen = path_transform_observer_compared = path_transform_observer_row_count = 0;
    unsigned char *tls = gate_tls_self();
    uint64_t original_time = 1234, original_previous = 2345, original_rng = 3456;
    uint32_t original_view = 0;
    memcpy(tls + GATE_TLS_LINUX_TIME, &original_time, 8);
    memcpy(tls + GATE_TLS_LINUX_PREVIOUS_TIME, &original_previous, 8);
    memcpy(tls + GATE_TLS_LINUX_RNG, &original_rng, 8);
    memcpy(tls + GATE_TLS_LINUX_VIEW, &original_view, 4);
    float matrix[16] = {1.0f};
    assert(path_transform_observer_call(0, from, matrix, to, 0) == matrix && path_transform_observer_test_native_calls == 1 && !path_transform_observer_test_live_calls);
    int entered = path_transform_observer_scope_enter();
    assert(entered);
    matrix[0] = 1.0f;
    assert(path_transform_observer_call(0, from, matrix, to, 0) == matrix && matrix[0] == 3.0f);
    assert(path_transform_observer_test_native_calls == 2 && path_transform_observer_test_live_calls == 1 && path_transform_observer_row_count == 1);
    assert(path_transform_observer_rows[0].from_id == 0x111 && path_transform_observer_rows[0].to_id == 0x222 && path_transform_observer_rows[0].live[0] == 4.0f);
    assert(!memcmp(tls + GATE_TLS_LINUX_TIME, &original_time, 8) && !memcmp(tls + GATE_TLS_LINUX_PREVIOUS_TIME, &original_previous, 8));
    assert(!memcmp(tls + GATE_TLS_LINUX_RNG, &original_rng, 8) && !memcmp(tls + GATE_TLS_LINUX_VIEW, &original_view, 4));
    memcpy(controller, &nav_vtable, 8);
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 0);
    assert(path_transform_observer_test_native_calls == 3 && path_transform_observer_test_live_calls == 1);
    memcpy(controller, &movement_vtable, 8);
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 1);
    assert(path_transform_observer_test_native_calls == 4 && path_transform_observer_test_live_calls == 1);
    uint32_t alternate_view = 1;
    memcpy(tls + GATE_TLS_LINUX_VIEW, &alternate_view, 4);
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 0);
    assert(path_transform_observer_test_native_calls == 5 && path_transform_observer_test_live_calls == 1);
    memcpy(tls + GATE_TLS_LINUX_VIEW, &original_view, 4);
    stats.issued = 11;
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 0);
    assert(path_transform_observer_test_native_calls == 6 && path_transform_observer_test_live_calls == 1);
    stats.issued = 10;
    double invalid_time = NAN;
    memcpy(manager + PATH_TRANSFORM_OBSERVER_MANAGER_TIME, &invalid_time, 8);
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 0);
    assert(path_transform_observer_test_native_calls == 7 && path_transform_observer_test_live_calls == 1);
    assert(path_transform_observer_failures == 1);
    path_transform_observer_failures = 0;
    memcpy(manager + PATH_TRANSFORM_OBSERVER_MANAGER_TIME, &time, 8);
    path_transform_observer_row_count = PATH_TRANSFORM_OBSERVER_ROWS;
    matrix[0] = 1.0f;
    path_transform_observer_call(0, from, matrix, to, 0);
    assert(path_transform_observer_test_native_calls == 8 && path_transform_observer_test_live_calls == 2);
    assert(path_transform_observer_dropped == 1 && path_transform_observer_failures == 1);
    path_transform_observer_scope_leave(entered);
    assert(!path_transform_observer_scope_thread);
    path_transform_observer_installed = 0;
    path_pass_open = 0;
    path_transform_observer_test_native = NULL;
    path_transform_observer_test_live = NULL;
    memcpy(LX(LX_PATH_MANAGER_VA), &previous_manager, 8);
    free(world_identities);
    world_identities = previous_identities;
    world_identity_sealed = previous_sealed;
    world_identity_count = previous_count;
    reset_session();
}
